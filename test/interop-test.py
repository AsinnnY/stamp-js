print('\n\033[1m▌ C. MP4: 下载真实视频 → stamp-js 写入 → exiftool + 手动解析验证\033[0m\n')

# 1. 下载真实 MP4
mp4_path = os.path.join(WORKDIR, 'test.mp4')
mp4_out = os.path.join(WORKDIR, 'test_tagged.mp4')
download_ok = False
try:
    print('  下载 sample-5s.mp4 ...')
    resp = requests.get('https://download.samplelib.com/mp4/sample-5s.mp4', timeout=30)
    resp.raise_for_status()
    with open(mp4_path, 'wb') as f:
        f.write(resp.content)
    if os.path.getsize(mp4_path) > 100000:
        download_ok = True
        check(f'下载真实 MP4 ({os.path.getsize(mp4_path)} bytes)', True)
except Exception as e:
    print(f'  \033[33m\u26a0 网络不可用 ({type(e).__name__})，回退到本地构造的 MP4\033[0m')

if not download_ok:
    # Fallback: build a real-structure MP4 locally (no network)
    subprocess.run(['node', '-e', f"""
import * as F from './test/fixtures.mjs';
import fs from 'node:fs';
const fx = F.buildMp4({{ layout: 'head', chunks: 8, chunkSize: 4096 }});
fs.writeFileSync('{mp4_path}', Buffer.from(fx.bytes));
"""], cwd=os.path.dirname(__file__) + '/..', capture_output=True, text=True, timeout=10,
        env={**os.environ, 'NODE_PATH': '.'})
    check(f'本地构造 MP4 ({os.path.getsize(mp4_path)} bytes)', os.path.getsize(mp4_path) > 0)

# 2. exiftool 读取原始文件信息
meta_before = exiftool_read(mp4_path)
if meta_before:
    print(f'  原始文件: {meta_before.get("QuickTime:MajorBrand", "?")}, '
          f'{meta_before.get("File:FileSize", "?")} bytes')

# 3. stamp-js 写入
mp4_tags = {
    'title': 'Interop MP4 Test',
    'artist': 'stamp-js Verification',
    'comment': 'Real MP4 from samplelib.com, tagged by stamp-js',
    'date': '2025-01-20T12:00:00Z',
    'software': 'stamp/0.1.0',
}
res = run_stamp_write(mp4_path, mp4_out, mp4_tags)
check('stamp-js 写入成功', res.get('ok'), res.get('error', ''))
if res.get('ok'):
    check(f'输出大小 {res["outputSize"]} > 输入 {res["inputSize"]}', res['outputSize'] >= res['inputSize'])
    check(f'只读了 {res["bytesRead"]} 字节（< 1MB）', res['bytesRead'] < 1024*1024,
          f'bytesRead={res["bytesRead"]}')
    check(f'strategy = {res.get("strategy", "?")}', bool(res.get('strategy')))

    # 4. exiftool 独立验证 MP4 元数据
    meta_after = exiftool_read(mp4_out)
    if meta_after:
        title = meta_after.get('QuickTime:Title', '') or meta_after.get('MP4:Title', '')
        artist = meta_after.get('QuickTime:Artist', '') or meta_after.get('MP4:Artist', '')
        comment = meta_after.get('QuickTime:Comment', '') or meta_after.get('MP4:Comment', '')
        check(f'exiftool 读到 MP4 Title = "{title}"', title == mp4_tags['title'], f'got "{title}"')
        check(f'exiftool 读到 MP4 Artist = "{artist}"', artist == mp4_tags['artist'], f'got "{artist}"')
        check(f'exiftool 读到 MP4 Comment', mp4_tags['comment'] in comment if comment else False, f'got "{comment}"')

    # 5. 手动解析 MP4 盒子结构
    with open(mp4_out, 'rb') as f:
        data = f.read()

    def u32(b, o):
        return struct.unpack('>I', b[o:o+4])[0]

    def fourcc(b, o):
        return b[o:o+4].decode('ascii', errors='replace')

    boxes = []
    pos = 0
    while pos + 8 <= len(data):
        size = u32(data, pos)
        hdr = 8
        tp = fourcc(data, pos + 4)
        if size == 1:
            size = struct.unpack('>Q', data[pos+8:pos+16])[0]
            hdr = 16
        elif size == 0:
            size = len(data) - pos
        if size < hdr or pos + size > len(data):
            break
        boxes.append((tp, size, pos))
        pos += size

    check(f'顶层盒子结构完整（{len(boxes)} 个）', len(boxes) > 0)
    print(f'    盒子: {", ".join(b[0] for b in boxes)}')

    # 找 moov
    moov = next((b for b in boxes if b[0] == 'moov'), None)
    if moov:
        check('moov 盒子存在', True)
        moov_data = data[moov[2]:moov[2]+moov[1]]
        # 找 udta
        p = 8
        udta_found = False
        while p + 8 <= len(moov_data):
            sz = u32(moov_data, p)
            tp = fourcc(moov_data, p + 4)
            if tp == 'udta':
                udta_found = True
                # 找 meta
                mp = p + 8
                while mp + 8 < p + sz:
                    msz = u32(moov_data, mp)
                    mtp = fourcc(moov_data, mp + 4)
                    if mtp == 'meta':
                        # 找 hdlr
                        kp = mp + 12
                        while kp + 8 < mp + msz:
                            ksz = u32(moov_data, kp)
                            ktp = fourcc(moov_data, kp + 4)
                            if ktp == 'hdlr':
                                hdlr_type = fourcc(moov_data, kp + 16)
                                check(f'meta/hdlr = {hdlr_type}', hdlr_type in ('mdir', 'mdta'))
                            if ktp == 'ilst':
                                # 读 ilst 条目
                                ip = kp + 8
                                entries = []
                                while ip + 8 < kp + ksz:
                                    isz = u32(moov_data, ip)
                                    iname = fourcc(moov_data, ip + 4)
                                    # 读 data 盒
                                    dp = ip + 8
                                    if dp + 16 <= ip + isz:
                                        dsz = u32(moov_data, dp)
                                        if fourcc(moov_data, dp + 4) == 'data' and dsz >= 16:
                                            val = moov_data[dp+16:dp+dsz].decode('utf-8', errors='replace')
                                            entries.append((iname.replace('\xa9', '©'), val[:40]))
                                    ip += isz
                                check(f'ilst 有 {len(entries)} 个条目', len(entries) >= 2)
                                for name, val in entries:
                                    print(f'      {name} = {val}')
                                    if name == '©nam':
                                        check(f'©nam = "{val}" == title', val == mp4_tags['title'])
                                    if name == '©ART':
                                        check(f'©ART = "{val}" == artist', val == mp4_tags['artist'])
                            kp += ksz
                    mp += msz
                break
            p += sz
        check('udta 盒子存在', udta_found)

    # 6. 验证 mdat 数据完整性（首尾字节）
    mdat_orig = next((b for b in boxes if b[0] == 'mdat'), None)
    if mdat_orig:
        # 读取原始文件的 mdat
        with open(mp4_path, 'rb') as f:
            orig_data = f.read()
        orig_mdat = None
        op = 0
        while op + 8 <= len(orig_data):
            sz = u32(orig_data, op)
            tp = fourcc(orig_data, op + 4)
            if sz == 1: sz = struct.unpack('>Q', orig_data[op+8:op+16])[0]
            elif sz == 0: sz = len(orig_data) - op
            if tp == 'mdat':
                orig_mdat = (op, sz)
                break
            op += sz
        if orig_mdat:
            # 比较 mdat 的前 1000 和后 1000 字节
            out_mdat_start = mdat_orig[2] + 8
            orig_mdat_start = orig_mdat[0] + 8
            mdat_len = min(mdat_orig[1] - 8, orig_mdat[1] - 8)
            head_match = data[out_mdat_start:out_mdat_start+1000] == orig_data[orig_mdat_start:orig_mdat_start+1000]
            tail_out = out_mdat_start + mdat_len - 1000
            tail_orig = orig_mdat_start + mdat_len - 1000
            tail_match = data[tail_out:tail_out+1000] == orig_data[tail_orig:tail_orig+1000]
            check('mdat 头部 1000 字节一致', head_match)
            check('mdat 尾部 1000 字节一致', tail_match)

    # 7. 幂等
    res2 = run_stamp_write(mp4_out, os.path.join(WORKDIR, 'test_tagged2.mp4'), mp4_tags)
    if res2.get('ok'):
        check('幂等：第二次写入大小一致', res2['outputSize'] == res['outputSize'],
              f'{res2["outputSize"]} vs {res["outputSize"]}')


# --------------------------------------------------------------------------
# D. Extended XMP：拿 exiftool 自己写出的分片做交叉验证
#
# exiftool 既是本套件的第三方基准，也是"扩展 XMP 命名空间到底是什么"的权威
# 来源之一。让它自己写一个 >64 KiB 的 XMP（exiftool 会按规范拆成
# StandardXMP + ExtendedXMP 分片），再把产物交给 stamp-js。
#
# 这条用例专门防一类隐患：库里识别分片用的常量如果写错（例如把
# xap/extension 写成 xmp/extension，或反过来），只要**库自己的夹具和断言跟着
# 一起写错**，整套测试依然全绿——只有拿第三方工具的真实产物来跑才拦得住。
# --------------------------------------------------------------------------
print('\n\033[1m▌ D. Extended XMP：exiftool 自行写出的分片 → stamp-js 处理 → exiftool 回读\033[0m\n')
try:
    from PIL import Image as _Image
    _base = os.path.join(WORKDIR, 'ext_base.jpg')
    _Image.new('RGB', (240, 180), (10, 60, 120)).save(_base, 'JPEG', quality=60)
    _src = os.path.join(WORKDIR, 'ext_xmp.jpg')
    subprocess.run(['exiftool', '-overwrite_original',
                    '-XMP-dc:Description=' + 'X' * 70000,
                    '-o', _src, _base],
                   capture_output=True, text=True, timeout=120)
    _blob = open(_src, 'rb').read()
    check('扩展 XMP：exiftool 确实写出了一个 xmp/extension 分片 + HasExtendedXMP',
          b'http://ns.adobe.com/xmp/extension/' in _blob and b'HasExtendedXMP' in _blob,
          f'size={len(_blob)}')

    _out = os.path.join(WORKDIR, 'ext_tagged.jpg')
    _script = f"""
import {{ writeTags, inspect, BlobSource }} from '{STAMP_JS}';
import fs from 'node:fs';
const blob = await fs.openAsBlob({json.dumps(_src)});
const before = await inspect(new BlobSource(blob));
const res = await writeTags(new BlobSource(blob), {{ title: 'ExtXmp', artist: 'asinnn' }});
if (!res.ok) {{ console.error(JSON.stringify({{ok:false,error:res.report.error}})); process.exit(1); }}
fs.writeFileSync({json.dumps(_out)}, Buffer.from(await res.blob.arrayBuffer()));
console.log(JSON.stringify({{ ok:true,
  fragments: (before.jpeg && before.jpeg.extendedXmpFragments) || 0,
  removed: (res.report.xmp && res.report.xmp.staleExtendedFragments) || 0 }}));
"""
    _r = subprocess.run(['node', '--input-type=module', '-e', _script],
                        capture_output=True, text=True, timeout=120)
    _res = json.loads(_r.stdout.strip()) if _r.returncode == 0 and _r.stdout.strip() else {'ok': False}
    check('扩展 XMP：写入成功', _res.get('ok') is True,
          (_r.stderr or '').strip()[:150])
    if _res.get('ok'):
        check('扩展 XMP：inspect() 认得这些分片', _res.get('fragments', 0) > 0,
              f"fragments={_res.get('fragments')}")
        check('扩展 XMP：写入时按过期分片清除', _res.get('removed', 0) > 0,
              f"removed={_res.get('removed')}")
        _outb = open(_out, 'rb').read()
        check('扩展 XMP：输出不再残留 xmp/extension 段',
              b'http://ns.adobe.com/xmp/extension/' not in _outb)
        check('扩展 XMP：输出不残留悬空的 HasExtendedXMP',
              b'HasExtendedXMP' not in _outb)
        _j = exiftool_read(_out) or {}
        # -G（不带数字）给出的是组名，XMP 标签的键是 'XMP:Title'；带 -G1/-G2
        # 时才是 'XMP-dc:Title'。两种都认，避免把键名差异当成功能失败。
        _title = _j.get('XMP:Title') or _j.get('XMP-dc:Title')
        check('扩展 XMP：exiftool 读回新标题', _title == 'ExtXmp', repr(_title))
        check('扩展 XMP：主图像仍可解码',
              _Image.open(_out).size == _Image.open(_src).size)
except Exception as _e:
    check('扩展 XMP 场景执行', False, str(_e)[:150])

# 清理
import shutil
shutil.rmtree(WORKDIR, ignore_errors=True)

print(f'\n\033[1m{"ALL PASSED" if FAIL == 0 else "SOME FAILED"}\033[0m  {PASS} passed, {FAIL} failed\n')
sys.exit(0 if FAIL == 0 else 1)
