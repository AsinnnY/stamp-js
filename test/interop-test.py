    check(f'只读了 {res["bytesRead"]} 字节', res['bytesRead'] > 0)

    # 3. exiftool 独立验证
    meta = exiftool_read(jpg_out)
    if meta:
        xmp_title = meta.get('XMP:Title', '')
        xmp_creator = meta.get('XMP:Creator', '')
        xmp_desc = meta.get('XMP:Description', '')
        xmp_source = meta.get('XMP:Source', '')
        xmp_rights = meta.get('XMP:Rights', '')
        xmp_create_date = meta.get('XMP:CreateDate', '')
        xmp_tool = meta.get('XMP:CreatorTool', '')
        check(f'exiftool 读到 XMP Title = "{xmp_title}"', xmp_title == tags['title'], f'got "{xmp_title}"')
        check(f'exiftool 读到 XMP Creator = "{xmp_creator}"', xmp_creator == tags['artist'])
        check(f'exiftool 读到 XMP Description 包含 comment', tags['comment'] in xmp_desc if xmp_desc else False)
        check(f'exiftool 读到 XMP Source = URL', xmp_source == tags['url'])
        check(f'exiftool 读到 XMP CreateDate (exiftool reformats to YYYY:MM:DD)', '2025:01:20' in xmp_create_date, f'got "{xmp_create_date}"')
        check(f'exiftool 读到 XMP CreatorTool = "{xmp_tool}"', xmp_tool == tags['software'])
    else:
        check('exiftool 读取成功', False, 'exiftool failed')

    # 4. Pillow 重新打开，验证图片完整性（重新加载原始文件比较）
    img_orig = Image.open(jpg_path)
    img2 = Image.open(jpg_out)
    check(f'Pillow 重新打开 JPEG: {img2.size} {img2.format}', img2.size == (800, 600) and img2.format == 'JPEG')
    px_orig = img_orig.load()
    px_new = img2.load()
    same = all(px_orig[x, y] == px_new[x, y] for x in range(0, 800, 100) for y in range(0, 600, 100))
    check('像素数据逐点一致（抽样）', same)

    # 5. 幂等
    res2 = run_stamp_write(jpg_out, os.path.join(WORKDIR, 'test_tagged2.jpg'), tags)
    if res2.get('ok'):
        check('幂等：第二次写入大小一致', res2['outputSize'] == res['outputSize'],
              f'{res2["outputSize"]} vs {res["outputSize"]}')


